def write_cards(out_dir: Path | None = None) -> list[Path]:
    """Write all cards to ``out_dir`` (defaults to repo root)."""
    out = out_dir or REPO_ROOT
    out.mkdir(parents=True, exist_ok=True)

    files: list[Path] = []
    for name, fn in (
        ("MODEL_CARD_NATIVE.md", model_card_native),
        ("MODEL_CARD_CODERSEC.md", model_card_codersec),
        ("DATASET_CARD.md", dataset_card),
    ):
        path = out / name
        path.write_text(fn(), encoding="utf-8")
        files.append(path)
    return files


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Generate XRFM model/dataset cards")
    parser.add_argument("--out-dir", default=".", help="output directory")
    args = parser.parse_args()
    written = write_cards(Path(args.out_dir))
    for p in written:
        print(f"wrote {p}")
