"""HF Model Card and Dataset Card generation for XRFM Phase 8 (GATE-8).

Generates publication-grade model cards and dataset cards from committed
JSON artifacts in ``docs/experiments/``. Every public claim traces 1-to-1
to a committed artifact so external researchers can audit and reproduce.

Usage::

    python -m xrfm.experiment.cards --out-dir .
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[3]
EXPERIMENTS_DIR = REPO_ROOT / "docs" / "experiments"


def _load_json(name: str) -> dict[str, Any]:
    path = EXPERIMENTS_DIR / name
    if not path.exists():
        return {}
    with open(path) as f:
        return json.load(f)  # type: ignore[no-any-return]


